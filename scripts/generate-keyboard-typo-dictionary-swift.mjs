import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { katakana, parseTsv } from "./validate-keyboard-typo-dictionary.mjs";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = join(repoRoot, "data", "keyboard-typo-dictionary.tsv");
const outputPath = join(
  repoRoot,
  "server-swift",
  "Sources",
  "azookey-server",
  "KeyboardTypoDictionary.swift",
);

function swiftString(value) {
  return JSON.stringify(value)
    .replaceAll("\\/", "/")
    .replaceAll("\\u2028", "\\u{2028}")
    .replaceAll("\\u2029", "\\u{2029}");
}

function scoreFor(row, tierIndex) {
  const base = {
    required: -6,
    core: -8,
    candidate: -10,
  }[row.selection_tier];
  if (base === undefined) throw new Error(`unsupported tier: ${row.selection_tier}`);
  return (base - tierIndex * 0.01).toFixed(2);
}

function lookupReading(row) {
  let reading = katakana(row.typed_reading);
  if (row.typed_keys.includes("-")) {
    const longVowelKeyCount = [...row.typed_keys].filter((key) => key === "-").length;
    const longVowelCount = [...reading].filter((character) => character === "ー").length;
    if (longVowelKeyCount !== longVowelCount) {
      throw new Error(`long-vowel keys must correspond to long-vowel marks: ${row.id}`);
    }
    reading = reading.replaceAll("ー", "-");
  }
  if (row.typed_keys.endsWith("n")) {
    if (!reading.endsWith("ン")) {
      throw new Error(`terminal n key must correspond to a terminal ん: ${row.id}`);
    }
    reading = `${reading.slice(0, -1)}n`;
  }
  return reading;
}

function generateSwift(rows) {
  const tierCounts = new Map();
  const entries = rows.map((row) => {
    const tierIndex = tierCounts.get(row.selection_tier) ?? 0;
    tierCounts.set(row.selection_tier, tierIndex + 1);
    return [
      "        DicdataElement(",
      `            word: ${swiftString(row.expected_candidate)},`,
      `            ruby: ${swiftString(lookupReading(row))},`,
      "            cid: CIDData.固有名詞.cid,",
      "            mid: MIDData.一般.mid,",
      `            value: ${scoreFor(row, tierIndex)},`,
      "            metadata: .isKeyboardTypoCorrection",
      "        ),",
    ].join("\n");
  });

  return `// Generated by scripts/generate-keyboard-typo-dictionary-swift.mjs.
// Do not edit directly. The source selection data is CC BY-SA 3.0; see
// data/keyboard-typo-dictionary.md and the keyboard-typo NOTICE files.

import KanaKanjiConverterModule

let keyboardTypoDictionaryEntryCount = ${rows.length}

func makeKeyboardTypoDictionaryEntries() -> [DicdataElement] {
    [
${entries.join("\n")}
    ]
}

func makeConversionDictionaryEntries(
    userEntries: [DicdataElement],
    experimentalTypoCorrectionEnabled: Bool
) -> [DicdataElement] {
    guard experimentalTypoCorrectionEnabled else {
        return userEntries
    }
    return userEntries + makeKeyboardTypoDictionaryEntries()
}

private func keyboardTypoDictionaryEntryKey(ruby: String, word: String) -> String {
    ruby + "\\u{0}" + word
}

private let keyboardTypoDictionaryEntryKeys = Set(
    makeKeyboardTypoDictionaryEntries().map {
        keyboardTypoDictionaryEntryKey(ruby: $0.ruby, word: $0.word)
    }
)

func disableLearningForKeyboardTypoDictionaryCandidates(
    _ candidates: [Candidate],
    experimentalTypoCorrectionEnabled: Bool
) -> [Candidate] {
    guard experimentalTypoCorrectionEnabled else {
        return candidates
    }
    return candidates.map { source in
        var candidate = source
        if candidate.data.contains(where: {
            keyboardTypoDictionaryEntryKeys.contains(
                keyboardTypoDictionaryEntryKey(ruby: $0.ruby, word: $0.word)
            )
        }) {
            candidate.isLearningTarget = false
        }
        return candidate
    }
}
`;
}

async function main() {
  const rows = parseTsv(await readFile(inputPath, "utf8"));
  const generated = generateSwift(rows);
  if (process.argv.includes("--check")) {
    const current = await readFile(outputPath, "utf8").catch(() => "");
    if (current !== generated) {
      throw new Error(`${outputPath} is not synchronized with ${inputPath}`);
    }
    process.stdout.write(`Keyboard typo dictionary Swift source is synchronized (${rows.length} entries).\n`);
    return;
  }
  await writeFile(outputPath, generated);
  process.stdout.write(`Generated ${outputPath} (${rows.length} entries).\n`);
}

export { generateSwift, lookupReading, scoreFor };

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
